import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {mkdtemp,mkdir,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {once} from 'node:events';
import path from 'node:path';
import assert from 'node:assert/strict';
const data=await mkdtemp(path.join(tmpdir(),'multi-ui-'));
const base='http://127.0.0.1:18031';
const server=spawn('.venv/bin/python',['tests/multicamera_ui_server.py','18031'],{env:{...process.env,PYTHONPATH:'.',CAMERA_DATA_DIR:data,DASHBOARD_PASSWORD:'',WA_PORT:'18032',CUDA_VISIBLE_DEVICES:''},stdio:['ignore','ignore','pipe']});
let logs='',browser;server.stderr.on('data',c=>logs+=c);
const api=async(path,method='GET',body)=>{const response=await fetch(base+path,{method,headers:{'Content-Type':'application/json','X-Casa-Request':'1'},body:body?JSON.stringify(body):undefined});assert.ok(response.ok,await response.clone().text());return response.json();};
try {
  for(let i=0;i<200;i++){try{if((await fetch(base+'/api/settings')).ok)break;}catch{}if(i===199)throw Error(logs);await new Promise(r=>setTimeout(r,200));}
  browser=await chromium.launch({executablePath:process.env.CHROME_PATH || '/opt/google/chrome/chrome',headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1360,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
  await page.goto(base);await page.waitForFunction(()=>document.querySelector('#live-image').naturalWidth===640);
  await page.locator('#add-camera').click();
  await page.locator('#camera-form [name=camera_name]').fill('Sala');
  await page.locator('#camera-form [name=camera_source]').fill(path.join(data,'second.avi'));
  await page.locator('#camera-form [type=submit]').click();
  await page.waitForURL('**/#settings');
  await page.waitForFunction(()=>document.querySelector('#settings-form [name=camera_name]').value==='Sala');
  const second=await page.locator('#camera-select').inputValue();assert.notEqual(second,'main');
  await page.locator('#settings-form [name=device]').selectOption('cpu');
  await page.locator('#settings-form [name=detection_fps]').fill('5');
  await page.locator('#save-settings').click();
  await page.locator('#pause-all-analysis').click();
  await page.locator('a[data-page=overview]').click();
  await page.locator('#toggle-monitor').click();
  await page.waitForFunction(()=>document.querySelector('#live-image').naturalWidth===800);
  assert.equal((await api('/api/cameras')).cameras.filter(c=>c.state==='online').length,2);
  const bad=await api('/api/cameras','POST',{camera_name:'Sem sinal',camera_source:'rtsp://127.0.0.1:1/missing',enabled:true,analysis_enabled:false});
  await page.waitForTimeout(1000);
  assert.equal((await api('/api/status?camera_id='+bad.id)).camera.state,'offline');
  assert.equal((await api('/api/status?camera_id='+second)).camera.state,'online');
  await api('/api/cameras/'+bad.id,'DELETE');
  await mkdir('test-results',{recursive:true});await page.screenshot({path:'test-results/multicamera-desktop.png',fullPage:true});
  await page.locator('#toggle-recording').click();
  await page.waitForFunction(()=>document.querySelector('#toggle-recording').textContent==='Parar gravação manual');
  await page.locator('#camera-select').selectOption('main');
  await page.waitForFunction(()=>document.querySelector('#live-image').naturalWidth===640);
  await page.locator('#toggle-recording').click();
  await page.waitForFunction(()=>document.querySelector('#toggle-recording').textContent==='Parar gravação manual');
  await page.waitForTimeout(1700);
  await page.locator('#toggle-recording').click();
  await page.waitForFunction(()=>document.querySelector('#toggle-recording').textContent==='Gravar manualmente');
  assert.equal((await api('/api/status?camera_id='+second)).camera.manual_recording,true);
  await page.locator('#camera-select').selectOption(second);
  await page.waitForFunction(()=>document.querySelector('#camera-title').textContent==='Sala');
  await page.locator('#remove-camera').click();
  await page.waitForFunction(()=>document.querySelector('#camera-select').value==='main');
  await page.waitForFunction(()=>document.querySelector('#live-image').naturalWidth===640);
  assert.equal((await api('/api/cameras')).cameras.length,1);
  const records=await api('/api/events?camera_id='+second);
  assert.equal(records.total,1);assert.equal(records.events[0].camera_name,'Sala');assert.ok(records.events[0].ended);
  await page.locator('a[data-page=history]').click();
  await page.locator('#history-camera').selectOption(second);
  await page.waitForFunction(()=>document.querySelector('#history-total').textContent==='1 registro(s)');
  assert.ok((await page.locator('#history-table').textContent()).includes('Sala'));
  assert.ok(!(await page.locator('#history-table').textContent()).includes('Cozinha'));
  await page.locator('#history-table [data-event]').first().click();
  await page.locator('#event-dialog').waitFor({state:'visible'});
  assert.ok((await page.locator('#event-number').textContent()).includes('Sala'));
  await page.locator('#event-dialog .close-dialog').click();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await mkdir('test-results',{recursive:true});await page.screenshot({path:'test-results/multicamera-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: cadastro/edição, duas câmeras, prévias distintas, gravações independentes, pausa global, remoção durante gravação, histórico filtrado preservado e tela móvel. Sem envios.');
} finally {await browser?.close();if(server.exitCode===null){server.kill('SIGTERM');await once(server,'exit');}await rm(data,{recursive:true,force:true});}
